// The brand board (07-04-PLAN.md Task 1, D-12/D-14) as a pure string builder.
//
// One board per concept per theme is what the user reads in 07-05 alongside the in-app captures.
// D-14 fixes its contents: the three lockups, a construction sheet on the real 24-unit grid, the
// 16/32/64/256 scale ladder and the favicon tile -- plus, from D-12, a preview of the Open Graph
// image. Pitfall 2 of 07-RESEARCH.md fixes what the board may NOT claim: Playwright cannot
// screenshot the browser's own tab strip, so the tile is shown on a SIMULATED bar that says so in
// words, and the real tab stays a manual check.
//
// THIS MODULE DRAWS NOTHING. Every mark on the board is `renderStaticSvg`/`tileSvg` output from
// 07-03 -- a render of the very components apps/web mounts -- so a board can never show a mark the
// app does not have. There is no geometry here: no coordinate, no radius, no angle. The only
// shapes this file assembles itself are the construction sheet's grid lines and guides, which are
// annotations over the mark rather than part of it.
//
// COLOUR. The board is the design system rendering itself: `tokensCss` is inlined verbatim and
// every surface, ink and hairline is a `var(--token)` reference. Exactly four literal colours may
// appear in the markup, and all four are the caller's: the tile's `background`/`ink` (D-11 -- the
// favicon is the one blue surface) and the OG image's `canvas`/`ink` (D-12 -- light ink on the
// dark canvas, regardless of which theme the board itself is in). The lockups are rendered with
// the literal string `currentColor`, which `static-svg.ts` deliberately does not contain, so the
// board's own `color: var(--ink)` is what paints them.
//
// The simulated tab strips need BOTH theme palettes on one page, whatever theme the board is in.
// `tokens.css` only carries a `[data-theme="dark"]` block (light lives under `:root`, which
// matches the document element only), so this module re-emits that same `:root` body -- taken from
// the passed `tokensCss`, never retyped -- as a `[data-theme="light"]` block. That is why both
// strips can sit side by side on a dark board and still be honest about their own palettes.
//
// NO SCRIPT, NO NETWORK, NO EMOJI (docs/ui-build-prompt.md section 9). The board is inert markup
// rendered by `page.setContent` with no navigation: no `<script>`, no event handler attribute, no
// `href`/`src`, no `url(` (so no web font and no remote image), no gradient, no shadow.

import {
  APERTURE_RADIUS,
  BASELINE,
  CONCEPT_META,
  GRID,
  MARGIN,
  STROKE,
  fmt,
  lockupLayout,
  monogramParts,
  wordmarkWidth,
  type ConceptId,
} from '../../packages/ui/src/brand/geometry.js';
import { renderStaticSvg, tileSvg } from '../../packages/ui/src/brand/static-svg.js';
import type { Theme } from './review-paths.js';

/** The review sizes D-14 names: a favicon, a rail icon, a card icon and a presentation size. */
export const BOARD_SCALES = [16, 32, 64, 256] as const;

/** `--r-md` (10px) on a 44px control -- the ratio `tileSvg` uses to keep an icon's corner inside
 *  the system's own radius family at every size (see static-svg.ts). */
const TILE_RADIUS_RATIO = 10 / 44;

/** The ink the board's own lockups inherit. `static-svg.ts` holds no colour literal at all, not
 *  even this one, precisely so the caller decides -- and on the board the caller wants the CSS
 *  cascade, i.e. `color: var(--ink)` on the body. */
const INHERIT = 'currentColor';

const TAGLINE = 'Your infrastructure, understood.';
const TAB_DISCLAIMER = 'Simulated browser tab — verify the real tab manually';
const FOOTER_NOTE = 'Generated by pnpm brand:boards — do not edit';

const CONSTRUCTION_SIZE = 480;

export interface BoardOptions {
  readonly concept: ConceptId;
  readonly theme: Theme;
  /** `packages/ui/tokens.css`, read from disk by the caller and inlined verbatim. */
  readonly tokensCss: string;
  /** D-11: the favicon tile's two colours (`--accent-fill` on `--on-accent`). */
  readonly tile: { readonly background: string; readonly ink: string };
  /** D-12: the OG image's two colours (the dark `--canvas` and the dark `--ink`). */
  readonly og: { readonly canvas: string; readonly ink: string };
}

// --- Rendering helpers -------------------------------------------------------------------------

/** `renderStaticSvg` renders at the components' own default size (the 24-unit grid), because the
 *  static export path has no size argument by design. The board needs the same mark at eight
 *  different sizes, so this rewrites the root element's `width`/`height` -- and only those, since
 *  nothing else in the rendered markup carries either attribute. The `viewBox` is untouched, so
 *  the result is the identical drawing at a different scale. */
const ROOT_SIZE_RE = / width="[\d.]+" height="[\d.]+"/;

function sized(svg: string, width: number, height: number): string {
  return svg.replace(ROOT_SIZE_RE, ` width="${fmt(width)}" height="${fmt(height)}"`);
}

function monogramSvg(concept: ConceptId, size: number, color: string): string {
  return sized(renderStaticSvg({ kind: 'monogram', concept, color }), size, size).trimEnd();
}

function lockupSvg(concept: ConceptId, height: number, color: string): string {
  const layout = lockupLayout(concept);
  const width = Math.round((height * layout.width) / layout.height);
  return sized(renderStaticSvg({ kind: 'lockup', concept, color }), width, height).trimEnd();
}

function wordmarkSvg(concept: ConceptId, height: number, color: string): string {
  const width = Math.round((height * wordmarkWidth(concept)) / GRID);
  return sized(renderStaticSvg({ kind: 'wordmark', concept, color }), width, height).trimEnd();
}

function tile(concept: ConceptId, size: number, options: BoardOptions): string {
  return tileSvg({
    concept,
    background: options.tile.background,
    ink: options.tile.ink,
    size,
    radiusRatio: TILE_RADIUS_RATIO,
  }).replace(/\n/g, '');
}

// --- Style -------------------------------------------------------------------------------------

/** Re-emits the `:root` declarations from the passed tokens CSS under `[data-theme="light"]`, so
 *  an element inside a dark board can opt into the light palette (the simulated light tab strip).
 *  The values are the file's own, lifted verbatim -- this module never states a token value. */
const ROOT_BLOCK_RE = /:root\s*\{([\s\S]*?)\}/;

function lightThemeBlock(tokensCss: string): string {
  const match = ROOT_BLOCK_RE.exec(tokensCss);
  if (match === null || match[1] === undefined) {
    // Fail loud: a silent fallback would render the "light" tab strip in dark tokens and quietly
    // misinform the very review this board exists for.
    throw new Error('board-html.ts: the tokens CSS carried no :root block to derive a light theme from');
  }
  return `[data-theme="light"] {${match[1]}}`;
}

