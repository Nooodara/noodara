// --- Sections ----------------------------------------------------------------------------------

function header(options: BoardOptions): string {
  const meta = CONCEPT_META[options.concept];
  return [
    '<header>',
    `<p class="caption mono">Concept ${meta.id.toUpperCase()} &middot; ${options.theme}</p>`,
    `<h1>${meta.name}</h1>`,
    `<p class="lead">${meta.meaning}</p>`,
    '</header>',
  ].join('');
}

function lockupsSection(options: BoardOptions): string {
  const { concept } = options;
  return [
    '<section data-board-section="lockups">',
    '<h2>Lockups</h2>',
    '<div class="row">',
    `<figure data-board-lockup="monogram"><div class="swatch">${monogramSvg(concept, 96, INHERIT)}</div><figcaption class="caption">Monogram</figcaption></figure>`,
    `<figure data-board-lockup="lockup"><div class="swatch">${lockupSvg(concept, 48, INHERIT)}</div><figcaption class="caption">Horizontal lockup</figcaption></figure>`,
    `<figure data-board-lockup="wordmark"><div class="swatch">${wordmarkSvg(concept, 48, INHERIT)}</div><figcaption class="caption">Wordmark</figcaption></figure>`,
    '</div>',
    '</section>',
  ].join('');
}

/** The 24x24 grid, the margin box and the baseline the mark is built on, as annotation lines under
 *  the real monogram. Straight lines and one rectangle only -- this is a ruler, not a drawing. */
function gridSvg(): string {
  const lines: string[] = [];
  for (let i = 0; i <= GRID; i += 1) {
    const at = fmt(i);
    lines.push(`<line x1="${at}" y1="0" x2="${at}" y2="${fmt(GRID)}" stroke="var(--hairline-strong)" stroke-width="0.04"/>`);
    lines.push(`<line x1="0" y1="${at}" x2="${fmt(GRID)}" y2="${at}" stroke="var(--hairline-strong)" stroke-width="0.04"/>`);
  }
  const inner = fmt(GRID - 2 * MARGIN);
  lines.push(
    `<rect x="${fmt(MARGIN)}" y="${fmt(MARGIN)}" width="${inner}" height="${inner}" fill="none" stroke="var(--ink-secondary)" stroke-width="0.08"/>`,
  );
  lines.push(
    `<line x1="0" y1="${fmt(BASELINE)}" x2="${fmt(GRID)}" y2="${fmt(BASELINE)}" stroke="var(--ink-secondary)" stroke-width="0.08"/>`,
  );
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" data-grid="${String(GRID)}" viewBox="0 0 ${fmt(GRID)} ${fmt(GRID)}"`,
    ` width="${String(CONSTRUCTION_SIZE)}" height="${String(CONSTRUCTION_SIZE)}" aria-hidden="true">`,
    lines.join(''),
    '</svg>',
  ].join('');
}

/** Every constant the mark is derived from, read from `geometry.ts` -- a D-16 adjustment round
 *  retunes the module and this sheet follows on the next `pnpm brand:boards`. */
const CONSTANTS: readonly (readonly [string, number])[] = [
  ['GRID', GRID],
  ['MARGIN', MARGIN],
  ['STROKE', STROKE],
  ['APERTURE_RADIUS', APERTURE_RADIUS],
  ['BASELINE', BASELINE],
];

function constructionSection(options: BoardOptions): string {
  const { concept } = options;
  const constants = CONSTANTS.map(([name, value]) => `<p class="mono">${name} = ${fmt(value)}</p>`).join('');
  const parts = monogramParts(concept)
    .map((part) => `<p class="mono">${part.part}</p>`)
    .join('');
  return [
    '<section data-board-section="construction">',
    '<h2>Construction</h2>',
    '<div class="row">',
    `<div class="construction">${gridSvg()}${monogramSvg(concept, CONSTRUCTION_SIZE, INHERIT)}</div>`,
    '<div>',
    '<p class="caption">Constants (geometry.ts)</p>',
    `<div class="list">${constants}</div>`,
    '<p class="caption">Parts, in DOM order</p>',
    `<div class="list">${parts}</div>`,
    '</div>',
    '</div>',
    '</section>',
  ].join('');
}

function scalesSection(options: BoardOptions): string {
  const items = BOARD_SCALES.map(
    (scale) =>
      `<figure data-board-scale="${String(scale)}"><div class="swatch">${monogramSvg(options.concept, scale, INHERIT)}</div><figcaption class="caption mono">${String(scale)} px</figcaption></figure>`,
  ).join('');
  return [
    '<section data-board-section="scales">',
    '<h2>Scales</h2>',
    `<div class="row">${items}</div>`,
    '</section>',
  ].join('');
}

function strip(theme: Theme, options: BoardOptions): string {
  return [
    `<figure data-strip="${theme}" data-theme="${theme}">`,
    '<div class="strip">',
    tile(options.concept, 16, options),
    '<span>Noodara</span>',
    tile(options.concept, 32, options),
    '</div>',
    `<figcaption class="caption">${TAB_DISCLAIMER}</figcaption>`,
    '</figure>',
  ].join('');
}

function tabStripsSection(options: BoardOptions): string {
  return [
    '<section data-board-section="tab-strips">',
    '<h2>Favicon tile</h2>',
    `<div class="row">${strip('light', options)}${strip('dark', options)}</div>`,
    '</section>',
  ].join('');
}

function ogSection(options: BoardOptions): string {
  const { og, concept } = options;
  return [
    '<section data-board-section="og-preview">',
    '<h2>Open Graph image</h2>',
    '<div data-board-og="1200x630" class="og-frame">',
    `<div class="og-inner" style="background: ${og.canvas}; color: ${og.ink};">`,
    lockupSvg(concept, 120, og.ink),
    `<p class="og-tagline">${TAGLINE}</p>`,
    '</div>',
    '</div>',
    `<p class="caption">1200 &times; 630, shown at half size.</p>`,
    '</section>',
  ].join('');
}

// --- Document ----------------------------------------------------------------------------------

/** Builds one complete, self-contained brand board. Pure: same options in, same bytes out. */
export function buildBoardHtml(options: BoardOptions): string {
  const meta = CONCEPT_META[options.concept];
  return [
    '<!doctype html>',
    `<html lang="en" data-theme="${options.theme}">`,
    '<head>',
    '<meta charset="utf-8">',
    `<title>Noodara brand board &mdash; concept ${meta.id.toUpperCase()} (${options.theme})</title>`,
    '<style>',
    options.tokensCss,
    lightThemeBlock(options.tokensCss),
    BOARD_CSS,
    '</style>',
    '</head>',
    '<body>',
    '<div class="board">',
    header(options),
    lockupsSection(options),
    constructionSection(options),
    scalesSection(options),
    tabStripsSection(options),
    ogSection(options),
    `<footer><p class="caption">${FOOTER_NOTE}</p></footer>`,
    '</div>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
}
